// Minimal self-hosted SCORM player using scorm-again (no SCORM Cloud).
// 1. Put SCORM .zip files in ./packages
// 2. npm install && npm start   (runs scripts/build.js, then this server)
// 3. Open http://localhost:3000
// Deploys to Vercel as-is: public/ is served by the CDN, this file becomes one function.

const express = require("express");
const path = require("path");
const courses = require("./courses.json"); // generated by scripts/build.js
const store = require("./progress-store");

const app = express();
const PORT = process.env.PORT || 3000;

// type "*/*": the final save on exit is sent via navigator.sendBeacon as text/plain
app.use("/api", express.json({ limit: "5mb", type: "*/*" }));
// Local only — on Vercel public/ (player, courses, lib) is served by the CDN and this is ignored
app.use(express.static(path.join(__dirname, "public")));

app.get("/api/courses", (req, res) => {
  res.json(courses);
});

app.get("/api/courses/:id", (req, res) => {
  const c = courses.find((x) => x.id === req.params.id);
  c ? res.json(c) : res.status(404).json({ error: "Course not found" });
});

// saved progress for resume
app.get("/api/progress/:id/:user", async (req, res) => {
  res.json(await store.get(req.params.id, req.params.user));
});

// scorm-again POSTs here on every commit
app.post("/api/progress/:id/:user", async (req, res) => {
  if (!req.body || typeof req.body !== "object") return res.status(400).json({ result: false, errorCode: 101 });
  await store.set(req.params.id, req.params.user, req.body);
  const core = req.body?.cmi?.core;
  console.log(`[commit] ${req.params.id} / ${req.params.user}`,
    core ? `status=${core.lesson_status} score=${core.score?.raw ?? ""}` :
           `completion=${req.body?.cmi?.completion_status} success=${req.body?.cmi?.success_status}`);
  res.json({ result: true, errorCode: 0 });
});

// Express 5 forwards rejected promises here (e.g. Redis unreachable)
app.use((err, req, res, next) => {
  console.error(err);
  res.status(500).json({ result: false, errorCode: 101, error: err.message });
});

if (require.main === module) {
  app.listen(PORT, () => console.log(`SCORM player running: http://localhost:${PORT} (progress: ${store.name})`));
}

module.exports = app;
